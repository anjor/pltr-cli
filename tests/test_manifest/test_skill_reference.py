"""The agent skill's generated reference (claude_skill/reference/) and its checks.

`scripts/generate_skill_reference.py` renders the reference from the command
manifest. These tests fail when the committed files are stale, and when a
hand-written skill file mentions a `pltr` command or option that doesn't exist.
"""

import os
import re
import subprocess
import sys
import textwrap

import pytest

REGENERATE = "Run: uv run python scripts/generate_skill_reference.py"

#: Reference files must stay small enough for an agent to load one on its own.
MAX_FILE_BYTES = 24_000


@pytest.fixture(scope="module")
def rendered(generator, manifest):
    return generator.render_files(manifest)


def test_skill_reference_is_up_to_date(generator, rendered):
    stale = generator.stale_files(rendered, generator.existing_files())
    assert not stale, (
        "claude_skill/reference/ doesn't match the command manifest: "
        f"{', '.join(stale)}.\n{REGENERATE}"
    )


def test_hand_written_skill_files_mention_only_real_commands(generator, manifest):
    problems = generator.check_hand_written(manifest)
    assert not problems, (
        "These pltr commands or options don't exist; fix the hand-written "
        "files (claude_skill/SKILL.md, README.md, workflows/, "
        "docs/user-guide/claude-skill.md, the README's 'Using pltr from "
        "agents' section):\n" + "\n".join(problems)
    )


def test_hand_written_files_are_checked(generator):
    texts = generator.hand_written_texts()
    assert {
        "claude_skill/SKILL.md",
        "claude_skill/README.md",
        "claude_skill/workflows/explore-data.md",
        "docs/user-guide/claude-skill.md",
        "README.md",
    } <= set(texts)
    assert texts["README.md"].startswith("## Using pltr from agents")
    assert len(generator.find_invocations(texts["claude_skill/SKILL.md"])) > 20


def test_generation_is_deterministic(generator, manifest, rendered):
    assert generator.render_files(manifest) == rendered


def test_generation_doesnt_depend_on_the_environment(tmp_path):
    """Another process, home, terminal, locale and hash seed: same files."""
    env = dict(os.environ)
    env.update(
        HOME=str(tmp_path),
        XDG_CONFIG_HOME=str(tmp_path / "config"),
        COLUMNS="20",
        LINES="3",
        TERM="dumb",
        LANG="C",
        LC_ALL="C",
        PYTHONHASHSEED="4242",
        PLTR_FORMAT="json",
        NO_COLOR="1",
    )
    script = os.path.join("scripts", "generate_skill_reference.py")
    root = os.path.dirname(os.path.dirname(os.path.dirname(__file__)))
    result = subprocess.run(
        [sys.executable, script, "--check"],
        cwd=root,
        env=env,
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stdout + result.stderr


def test_files_survive_the_pre_commit_hooks(rendered):
    """No trailing whitespace, one final newline, LF only (the hooks' rules)."""
    for path, content in rendered.items():
        assert content.endswith("\n") and not content.endswith("\n\n"), path
        assert "\r" not in content and "\t" not in content, path
        for number, line in enumerate(content.splitlines(), 1):
            assert line == line.rstrip(), f"{path}:{number} has trailing whitespace"


def test_files_are_small_and_marked_generated(rendered):
    for path, content in rendered.items():
        assert content.startswith(
            "<!-- Generated by scripts/generate_skill_reference.py"
        )
        size = len(content.encode("utf-8"))
        assert size <= MAX_FILE_BYTES, (
            f"{path} is {size} bytes; split it (see SPLIT_NAMESPACE_COMMANDS)"
        )


def test_every_visible_command_has_one_entry(manifest, rendered):
    headings = [
        line[4:]
        for content in rendered.values()
        for line in content.splitlines()
        if line.startswith("### ")
    ]
    visible = [e["path"] for e in manifest["commands"] if not e["hidden"]]
    assert sorted(headings) == sorted(visible)
    assert "pltr shell interactive" not in headings  # hidden


def test_index_links_every_file(rendered):
    links = re.findall(r"\]\(((?:curated|api)/[^)]+\.md)\)", rendered["index.md"])
    assert sorted(links) == sorted(path for path in rendered if path != "index.md")
    assert len(links) == len(set(links))


def test_entries(rendered):
    folder = rendered["curated/folder.md"]
    assert (
        textwrap.dedent(
            """\
        ### pltr folder list

        List the resources directly inside a folder.

        `pltr folder list FOLDER_RID [OPTIONS]`

        - `FOLDER_RID`: RID of the folder, project or space to list (the API can't list the root folder: find spaces with 'pltr space list').
        - paged · SDK: `filesystem.Folder.children`
        """
        )
        in folder
    )
    space = rendered["curated/space.md"]
    assert (
        "- beta · **destructive** (asks first; `--yes` skips) · SDK: `filesystem.Space.delete`"
        in space
    )
    content = rendered["api/datasets.md"]
    assert (
        "- output: binary (to `--output FILE` or a pipe) · SDK: `datasets.Dataset.File.content`"
        in content
    )
    # Curated binary commands: by @pltr_command(binary=True).
    assert (
        "- output: binary (to `--output FILE` or a pipe) · SDK: `audit.Organization.LogFile.content`"
        in rendered["curated/audit.md"]
    )
    assert (
        "- beta · output: binary (to `OUTPUT_PATH`, `-` for stdout) · SDK: `media_sets.MediaSet.retrieve`"
        in rendered["curated/media-sets.md"]
    )
    assert "- local (no Foundry call)" in rendered["curated/commands.md"]
    # Large namespaces are split by resource.
    assert "api/ontologies/action.md" in rendered
    assert "api/ontologies.md" not in rendered
    action = rendered["api/ontologies/action.md"]
    assert (
        "`--parameters` JSON (required): Dict[ParameterId, Optional[DataValue]]."
        in action
    )
    assert "](../../index.md)" in action


# ------------------------------------------------------- the command checker

MARKDOWN = textwrap.dedent(
    """\
    Run `pltr folder get RID --format json` or `pltr commands search <words>`.

    ```bash
    # a comment mentioning pltr nothing
    pltr folder list ri.compass.main.folder.0 \\
      --all --format json | jq .   # pltr is fine here
    RID=$(pltr resource get-by-path "/My Space/x" -f json | jq -r .rid)
    pltr dataset gett "$RID"
    pltr folder get "$RID" --colour
    pltr <group> --help
    pltr api --help
    pltr folder
    pltr dataset get ri.foundry.main.dataset.<id> --format json > out.json
    ```
    """
)


def test_find_invocations(generator):
    found = generator.find_invocations(MARKDOWN)
    assert found == [
        (1, ["folder", "get", "RID", "--format", "json"]),
        (1, ["commands", "search", "<words>"]),
        (
            5,
            ["folder", "list", "ri.compass.main.folder.0", "--all", "--format", "json"],
        ),
        (7, ["resource", "get-by-path", "/My Space/x", "-f", "json"]),
        (8, ["dataset", "gett", "$RID"]),
        (9, ["folder", "get", "$RID", "--colour"]),
        (10, ["<group>", "--help"]),
        (11, ["api", "--help"]),
        (12, ["folder"]),
        (13, ["dataset", "get", "ri.foundry.main.dataset.<id>", "--format", "json"]),
    ]


def test_check_invocation(generator, manifest):
    def check(*words):
        return generator.check_invocation(manifest, list(words))

    assert check("folder", "get", "RID", "--format=json") == []
    assert check("folder", "list", "R", "--all", "-f", "json", "--page-size", "5") == []
    assert check("commands", "search", "<words>") == []
    assert check("<group>", "--help") == []
    assert check("api", "--help") == []
    assert check("folder") == []  # a group on its own shows its help
    assert check("--version") == []
    assert check("dataset", "gett", "$RID") == [
        "'pltr dataset gett' is not a pltr command"
    ]
    assert check("folder", "get", "R", "--colour") == [
        "'pltr folder get' has no option --colour"
    ]
    # Hidden, deprecated aliases don't count as documented options.
    assert check("space", "delete", "R", "--confirm") == [
        "'pltr space delete' has no option --confirm"
    ]
    assert check("api", "--format", "json") == [
        "'pltr api' is a group: 'pltr api --format json' runs no command"
    ]


def test_write_files_replaces_the_directory(generator, tmp_path):
    (tmp_path / "old.md").write_text("hand-written\n")
    (tmp_path / "gone").mkdir()
    (tmp_path / "gone" / "x.md").write_text("x\n")
    files = {"index.md": "index\n", "api/a.md": "a\n"}
    generator.write_files(files, tmp_path)
    assert generator.existing_files(tmp_path) == files
    assert not (tmp_path / "gone").exists()
    assert generator.stale_files(files, generator.existing_files(tmp_path)) == []
    assert generator.stale_files({"index.md": "new\n"}, files) == [
        "api/a.md",
        "index.md",
    ]


def test_resource_parameters_say_they_take_a_path(generator):
    argument = {
        "name": "dataset_rid",
        "type": "string",
        "required": True,
        "multiple": False,
        "acceptsPath": True,
        "resourceKind": "dataset",
        "help": "Dataset RID. A Compass path such as /Space/Project/name works too.",
    }
    assert generator.render_argument(argument) == (
        "- `DATASET_RID` (RID or path): Dataset RID."
    )
    option = {
        "name": "parent",
        "flags": ["--parent"],
        "type": "string",
        "required": True,
        "multiple": False,
        "acceptsPath": True,
        "resourceKind": "folder",
        "help": "Folder. A Compass path such as /Space/Project/name works too.",
    }
    assert generator.render_option(option) == (
        "- `--parent` RID|PATH (required): Folder."
    )
