"""Shell completion commands for pltr CLI.

The scripts these commands print or install call the ``pltr`` executable
with Typer's completion protocol (``_PLTR_COMPLETE=complete_bash`` and so
on), which is what the ``pltr`` entry point (a Typer app) answers. They are
generated by Typer itself, so they follow the installed Typer version.

These commands make no Foundry API call. The script goes to stdout;
messages and activation instructions go to stderr.
"""

import os
from pathlib import Path
from typing import Optional

import click
import typer
from typing_extensions import Annotated

from ..contract import info, pltr_command, success

app = typer.Typer(help="Manage shell completions for pltr CLI")

#: Shells pltr can install completion scripts for.
SHELLS = ("bash", "zsh", "fish")
PROG_NAME = "pltr"
#: Environment variable the completion scripts set to ask ``pltr`` for completions.
COMPLETE_VAR = "_PLTR_COMPLETE"

ShellOption = Annotated[
    Optional[str],
    typer.Option(
        "--shell",
        "-s",
        click_type=click.Choice(SHELLS, case_sensitive=False),
        help="Shell: bash, zsh or fish (default: detected from $SHELL).",
        show_default=False,
    ),
]


def get_shell_from_env() -> Optional[str]:
    """Detect the current shell from environment."""
    shell_path = os.environ.get("SHELL", "")
    if "bash" in shell_path:
        return "bash"
    elif "zsh" in shell_path:
        return "zsh"
    elif "fish" in shell_path:
        return "fish"
    return None


def _resolve_shell(shell: Optional[str]) -> str:
    """The shell to use: --shell, else the one $SHELL names."""
    if shell:
        return shell.lower()
    detected = get_shell_from_env()
    if detected is None:
        raise typer.BadParameter(
            "could not detect your shell from $SHELL; pass --shell bash, zsh or fish.",
            param_hint="'--shell'",
        )
    return detected


@app.command()
@pltr_command()
def install(
    shell: ShellOption = None,
    path: Annotated[
        Optional[Path],
        typer.Option(
            "--path",
            "-p",
            help="Where to write the completion file (default: the shell's usual place).",
            show_default=False,
        ),
    ] = None,
):
    """Install shell completions for pltr CLI.

    Writes the completion script for your shell (detected from $SHELL unless
    you pass --shell) and explains how to activate it. Restart your shell or
    source the file afterwards.

    Examples:
        pltr completion install
        pltr completion install --shell bash
        pltr completion install --shell zsh --path ~/.config/custom/completions/_pltr
    """
    detected = shell is None
    shell = _resolve_shell(shell)
    if detected:
        info(f"Detected shell: {shell}")

    target = path if path is not None else get_default_completion_path(shell)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(generate_completion_script(shell))
    success(f"Completion file written to: {target}")
    show_activation_instructions(shell, target)


@app.command()
@pltr_command()
def show(shell: ShellOption = None):
    """Print the completion script for a shell.

    Prints the script without installing it, for manual installation, e.g.
    eval "$(pltr completion show --shell bash)" in ~/.bashrc.
    """
    typer.echo(generate_completion_script(_resolve_shell(shell)), nl=False)


def generate_completion_script(shell: str) -> str:
    """Generate the completion script for ``shell`` (bash, zsh or fish)."""
    from typer.completion import get_completion_script

    if shell not in SHELLS:
        raise ValueError(f"Unsupported shell: {shell}")
    script = get_completion_script(
        prog_name=PROG_NAME, complete_var=COMPLETE_VAR, shell=shell
    )
    if shell == "zsh":
        script = _complete_when_autoloaded(script)
    return script.rstrip("\n") + "\n"


_ZSH_COMPDEF = f"compdef _{PROG_NAME}_completion {PROG_NAME}"


def _complete_when_autoloaded(script: str) -> str:
    """Make the zsh script also complete on the first TAB when autoloaded.

    ``install`` puts the script on zsh's fpath (as ``_pltr``), where compinit
    autoloads it on the first completion. Typer's script then only registers
    its function, so that first TAB would complete nothing; this runs the
    function straight away in that case, as click's zsh template does.
    """
    lines = script.rstrip("\n").splitlines()
    if not lines or lines[-1].strip() != _ZSH_COMPDEF:
        return script  # a Typer version with a different template: keep it
    lines[-1:] = [
        "if [[ $zsh_eval_context[-1] == loadautofunc ]]; then",
        "  # autoloaded from fpath on the first completion: complete now",
        f'  _{PROG_NAME}_completion "$@"',
        "else",
        f"  {_ZSH_COMPDEF}",
        "fi",
    ]
    return "\n".join(lines) + "\n"


def get_default_completion_path(shell: str) -> Path:
    """Get the default path for completion file installation."""
    home = Path.home()

    if shell == "bash":
        # Try bash-completion paths
        paths = [
            home / ".local" / "share" / "bash-completion" / "completions" / "pltr",
            home / ".bash_completion.d" / "pltr",
            Path("/etc/bash_completion.d/pltr"),
        ]
        # Use first writable path
        for p in paths[:-1]:  # Skip system path for user installs
            if p.parent.exists() or not p.parent.parent.exists():
                return p
        return paths[0]

    elif shell == "zsh":
        # Zsh completion paths
        return home / ".zfunc" / "_pltr"

    elif shell == "fish":
        # Fish completion path
        return home / ".config" / "fish" / "completions" / "pltr.fish"

    else:
        raise ValueError(f"Unknown shell: {shell}")


def show_activation_instructions(shell: str, path: Path) -> None:
    """Explain on stderr how to activate the installed completions."""
    if shell == "bash":
        text = f"""To activate completions, add this to your ~/.bashrc:

    # Load pltr completions
    if [ -f {path} ]; then
        source {path}
    fi

Then reload your shell (source ~/.bashrc) or start a new terminal session."""
    elif shell == "zsh":
        text = f"""To activate completions, add this to your ~/.zshrc:

    # Add the completion directory and initialize completions
    fpath=({path.parent} $fpath)
    autoload -Uz compinit && compinit

Then reload your shell (source ~/.zshrc) or start a new terminal session."""
    else:
        text = f"""Fish loads completions automatically from:
    {path}

If they don't work yet, reload your shell (exec fish) or start a new terminal session."""
    info(text)


@app.command()
@pltr_command()
def uninstall(shell: ShellOption = None):
    """Remove the completion file 'pltr completion install' wrote."""
    path = get_default_completion_path(_resolve_shell(shell))

    if path.exists():
        path.unlink()
        success(f"Removed completion file: {path}")
        info("Remember to remove any lines that source it from your shell config.")
    else:
        info(f"No completion file found at: {path}")
